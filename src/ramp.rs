//! RA2 的 21 种坡型：每格四个角相对**本格 level** 抬升几层。
//!
//! 来源：`I:\bevy\RA2REASM\src\engine\world.cpp:724-755`（`kRampCorners` /
//! `rampCornerHeights`）。表的四项顺序是 **top / right / bottom / left**，
//! 正好是等距菱形在屏幕上的四个尖点，也正好是 (u,v) 的
//! (0,0) / (1,0) / (1,1) / (0,1) —— u 沿 +rx，v 沿 +ry。
//!
//! 【为什么 level 是低端而不是高端】RA2 的砖图固定画在 60×30 画布里，菱形四个尖点
//! 的位置是死的。抬升角只会让投影**上移**（落进画布），如果 level 记的是高端，
//! 低角就得往下移 15px、掉出画布。`Slope01.tem` 实测有效像素在 y = 0..13，
//! 一点没超出，所以 level 是低角，四角高度 = level + 表里的值。
//!
//! 17..20 是鞍形（对角两高两低），没有单一平面。表照样留着：几何按四角双线性插值，
//! 贴图逆推也按同一个四边形算。

/// 表的下标上限（含）。
pub const RAMP_TYPES: usize = 21;

/// `[top, right, bottom, left]`，单位 = 层。
pub const RAMP_CORNERS: [[i8; 4]; RAMP_TYPES] = [
    [0, 0, 0, 0], // 0 平
    [0, 1, 1, 0], // 1 单向上坡
    [0, 0, 1, 1], // 2
    [1, 0, 0, 1], // 3
    [1, 1, 0, 0], // 4
    [0, 0, 1, 0], // 5 对角
    [0, 0, 0, 1], // 6
    [1, 0, 0, 0], // 7
    [0, 1, 0, 0], // 8
    [0, 1, 1, 1], // 9
    [1, 0, 1, 1], // 10
    [1, 1, 0, 1], // 11
    [1, 1, 1, 0], // 12
    [0, 1, 2, 1], // 13 陡坡（跨两层）
    [1, 0, 1, 2], // 14
    [2, 1, 0, 1], // 15
    [1, 2, 1, 0], // 16
    [0, 1, 0, 1], // 17 鞍形
    [1, 0, 1, 0], // 18
    [0, 1, 0, 1], // 19
    [1, 0, 1, 0], // 20
];

/// 四角的抬升层数 `[top, right, bottom, left]`。越界按平地处理。
pub fn corner_heights(ramp: u8) -> [i8; 4] {
    RAMP_CORNERS
        .get(ramp as usize)
        .copied()
        .unwrap_or([0, 0, 0, 0])
}

/// 这一格是不是斜的（需要真几何 + 逆推贴图）。
pub fn is_sloped(ramp: u8) -> bool {
    corner_heights(ramp).iter().any(|&v| v != 0)
}
